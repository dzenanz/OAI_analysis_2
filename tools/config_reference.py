"""
Write docs/config.md, the reference of every config setting, from the stage classes themselves.

Usage:
    python tools/config_reference.py           # rewrite docs/config.md
    python tools/config_reference.py --check   # exit 1 if docs/config.md is out of date

Each stage's description is its docstring, and each parameter's is the comment next to (or above) its field.
"""
import argparse
import inspect
import io
import sys
import textwrap
import tokenize
from dataclasses import MISSING, fields
from pathlib import Path

import yaml

from oai_analysis import registry
from oai_analysis.config import BIOMARKER_EXTRACTORS, SINGLE_STAGES
from oai_analysis.pipeline import DEFAULT_BIOMARKER_EXTRACTORS, DEFAULT_STAGES

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "config.md"

HEADER = """\
# Config reference

<!-- Generated by tools/config_reference.py from the stage classes; edit those, then rerun it. -->

A config is a YAML file. `project.yaml` is one, and `oai-analysis IMAGE OUT left --config FILE` reads one.
Only the settings that differ from the defaults are needed: a setting that is left out keeps its default, and a stage
given without a `name` keeps the default implementation. `oai-analysis config dump` prints the full config.

```yaml
pipeline:
  registerer: {finetune_steps: 5}               # change one parameter of the default registerer
  thickness_estimator: {name: distance_transform}  # use another implementation
device: cuda
```

## Top-level settings

| Setting | Default | Meaning |
|---|---|---|
| `pipeline` | | The stages, below. |
| `device` | `auto` | `cuda`, `cuda:1`, `cpu` or `auto`. `auto` uses the GPU, and a project stops if there is none rather than run on the CPU (much slower) without being asked. |

These are read by a project (`oai-analysis init` writes them to `project.yaml`), not by the single-image command:

| Setting | Default | Meaning |
|---|---|---|
| `data_root` | none | The folder that the `input` paths in `cases.csv` are relative to, e.g. `O:/OAI`. |
| `batch_size` | `8` | Cases that go through preprocessing, segmentation and registration together, so each network is loaded and used for all of them in turn. A batch holds about 0.5 GB per case in memory. `run --batch-size N` overrides it. |
| `retention` | `checkpoints` | What is kept on disk. `checkpoints`: each step's outputs, enough to resume from any step. `all`: also the stages' intermediate outputs (e.g. `FC_inner.vtk`). `final`: once a case finishes, only the atlas-mapped meshes, the biomarkers and the provenance. |
| `storage.image_format` | `nrrd` | `nrrd` or `nii.gz`. Both are compressed and about the same size; NIfTI stores the image position in single precision, so resuming from it can change results slightly. |
| `storage.transform_format` | `h5` | `h5` (compressed, about 70 MB) or `tfm` (text, about 300 MB, readable). |

## Stages

Every stage has a `name` and its parameters. Some parameters are marked:
- *check*: a threshold of the stage's sanity checks. Changing it rechecks the saved outputs without redoing the step.
- *speed*: changes how fast the stage runs, not what it computes. Changing it does not make outputs outdated.

Changing any other parameter makes the step, and every step after it, outdated, so `run` redoes them.
"""

KIND_TITLES = {
    "preprocessor": "`preprocessor`: read and prepare the image",
    "segmenter": "`segmenter`: cartilage probability maps",
    "registerer": "`registerer`: register the image to the atlas",
    "mesh_generator": "`mesh_generator`: cartilage surfaces",
    "thickness_estimator": "`thickness_estimator`: thickness on the surfaces",
    "atlas_mapper": "`atlas_mapper`: carry the thickness onto the atlas surface",
    "biomarker_extractor": "`biomarker_extractors`: results computed from everything above (a list)",
}


def field_comments(cls) -> dict[str, str]:
    """The comment of each field in the class body: on the same line, or on the lines right above it."""
    comments = {}
    source = textwrap.dedent(inspect.getsource(cls))
    above, line_comment = [], {}
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type == tokenize.COMMENT:
            line_comment[token.start[0]] = token.string.lstrip("#").strip()
    lines = source.splitlines()
    for number, line in enumerate(lines, start=1):
        stripped = line.strip()
        if stripped.startswith("#"):
            above.append(line_comment[number])
            continue
        name = stripped.split(":", 1)[0]
        if ":" in stripped and name.isidentifier() and line.startswith("    ") and not line.startswith("     "):
            text = line_comment.get(number) or " ".join(above)
            if text:
                comments[name] = text
        above = []
    return comments


def all_comments(classes) -> dict[str, str]:
    """Field comments of every class, so a field without its own comment can take one of the same name elsewhere."""
    shared = {}
    for cls in classes:
        for name, text in field_comments(cls).items():
            shared.setdefault(name, text)
    return shared


def flow(value) -> str:
    if isinstance(value, tuple):
        value = list(value)
    return yaml.safe_dump(value, default_flow_style=True, width=1000).strip().removesuffix("...").strip()


def stage_section(cls, default: bool, shared: dict[str, str]) -> str:
    title = f"#### `{cls.name}`" + (" (default)" if default else "")
    doc = inspect.cleandoc(cls.__doc__ or "")
    own = field_comments(cls)
    rows = []
    for f in fields(cls):
        if f.name.startswith("_"):
            continue
        value = f.default if f.default is not MISSING else f.default_factory()
        marks = (["check"] if f.name in cls.check_params else []) + \
                (["speed"] if f.name in cls.performance_params else [])
        meaning = own.get(f.name) or shared.get(f.name, "")
        meaning = (meaning[0].upper() + meaning[1:]) if meaning else ""
        if marks:
            meaning = f"*{', '.join(marks)}*. {meaning}".strip()
        rows.append(f"| `{f.name}` | `{flow(value)}` | {meaning.replace('|', '&#124;')} |")
    parts = [title, "", f"`{cls.__module__}.{cls.__qualname__}`", ""]
    if doc:
        parts += [doc, ""]
    if rows:
        parts += ["| Parameter | Default | Meaning |", "|---|---|---|", *rows, ""]
    else:
        parts += ["No parameters.", ""]
    return "\n".join(parts)


def reference() -> str:
    defaults = {kind: cls for kind, cls in DEFAULT_STAGES.items()}
    default_extractors = set(DEFAULT_BIOMARKER_EXTRACTORS)
    kinds = [*SINGLE_STAGES, "biomarker_extractor"]
    # only the stages that come with oai-analysis, not those of plugins installed here
    classes = {kind: [registry.get(kind, name) for name in registry.available(kind)] for kind in kinds}
    classes = {kind: [cls for cls in group if cls.__module__.startswith("oai_analysis.")]
               for kind, group in classes.items()}
    shared = all_comments(cls for group in classes.values() for cls in group)
    out = [HEADER]
    for kind in kinds:
        out += [f"### {KIND_TITLES[kind]}", ""]
        group = classes[kind]
        is_default = (lambda c: c in default_extractors) if kind == "biomarker_extractor" else \
            (lambda c, kind=kind: c is defaults[kind])
        for cls in sorted(group, key=lambda c: (not is_default(c), c.name)):
            out.append(stage_section(cls, is_default(cls), shared))
    return "\n".join(out).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Exit 1 if docs/config.md is out of date")
    args = parser.parse_args()
    text = reference()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUTPUT} is out of date; run python tools/config_reference.py")
            return 1
        return 0
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
